class AIInvestigationSchema(BaseModel):
    """Strict schema for validating raw JSON responses generated by LLMs."""
    incident_summary: str = Field(..., description="Synthesis of verified observations")
    confidence: float = Field(default=0.85, ge=0.0, le=1.0)
    observed_evidence: List[str] = Field(default_factory=list)
    likely_attack_pattern: Optional[str] = None
    mitre_techniques: List[Dict[str, Any]] = Field(default_factory=list)
    root_cause_hypothesis: Optional[str] = None
    investigation_steps: List[str] = Field(default_factory=list)
    prioritized_recommendations: List[str] = Field(default_factory=list)
    evidence_references: List[Dict[str, Any]] = Field(default_factory=list)
    analyst_warning: Optional[str] = None
    feature_attributions: Optional[List[Dict[str, Any]]] = Field(default_factory=list)
    anomaly_deviations: Optional[List[Dict[str, Any]]] = Field(default_factory=list)

    @classmethod
    def sanitize_raw_llm_dict(cls, data: Dict[str, Any]) -> "AIInvestigationSchema":
        """Clean and validate raw dictionary returned by LLM, backfilling missing fields."""
        if not isinstance(data, dict):
            data = {}

        # 1. Clean techniques
        raw_techs = data.get("mitre_techniques") or []
        cleaned_techs = []
        for t in raw_techs:
            if isinstance(t, str):
                cleaned_techs.append({"technique_id": t, "name": t})
            elif isinstance(t, dict):
                cleaned_techs.append({
                    "technique_id": t.get("technique_id") or t.get("id") or "T0000",
                    "name": t.get("name") or "Unknown"
                })

        # 2. Confidence bounding
        raw_conf = data.get("confidence", 0.85)
        try:
            conf = float(raw_conf)
            if conf > 1.0 and conf <= 100.0:
                conf = conf / 100.0
            conf = float(max(0.0, min(1.0, conf)))
        except (ValueError, TypeError):
            conf = 0.85

        # 3. String & list sanitization
        def to_str_list(val: Any) -> List[str]:
            if isinstance(val, list):
                return [str(x) for x in val if x]
            if isinstance(val, str) and val.strip():
                return [val.strip()]
            return []

        summary = str(data.get("incident_summary") or data.get("investigation_summary") or "Investigation completed.")
        steps = to_str_list(data.get("investigation_steps") or data.get("recommended_steps") or ["Monitor traffic."])
        recs = to_str_list(data.get("prioritized_recommendations") or data.get("recommended_actions") or ["Review firewall logs."])
        evidence = to_str_list(data.get("observed_evidence") or [])

        raw_refs = data.get("evidence_references") or []
        cleaned_refs = []
        for r in raw_refs:
            if isinstance(r, dict):
                cleaned_refs.append(r)
            elif isinstance(r, str):
                cleaned_refs.append({"document_id": r, "title": r})

        return cls(
            incident_summary=summary,
            confidence=conf,
            observed_evidence=evidence,
            likely_attack_pattern=data.get("likely_attack_pattern"),
            mitre_techniques=cleaned_techs,
            root_cause_hypothesis=data.get("root_cause_hypothesis"),
            investigation_steps=steps,
            prioritized_recommendations=recs,
            evidence_references=cleaned_refs,
            analyst_warning=data.get("analyst_warning"),
            feature_attributions=data.get("feature_attributions") or [],
            anomaly_deviations=data.get("anomaly_deviations") or []
        )


